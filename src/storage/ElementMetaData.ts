/**
 * @file ElementMetaData.ts
 * @description Strict type definitions for the "training data" that the
 *              self-healing engine consumes. Every successful interaction
 *              performed by {@link SmartPage} is snapshotted into one of
 *              these records and persisted through an {@link IMetadataStore}
 *              implementation.
 */

/**
 * Contextual signals harvested from the element's immediate surroundings.
 *
 * Anchor context is what allows the engine to identify the *semantic role*
 * of an element even when its own attributes mutate (e.g. the id/class
 * names are re-generated by a new build tool). A login button's `id` may
 * change, but the wrapping `<label>` and sibling "Email" field are far
 * more stable signals of intent.
 */
export interface AnchorContext {
  /** Tag name of the direct parent, e.g. "form", "div". */
  parentTag?: string;
  /** Trimmed text nodes that belong DIRECTLY to the parent (excluding
   *  descendant text). Useful for panels/cards with a title. */
  parentText?: string;
  /** Non-empty, trimmed `innerText` of each sibling node. */
  siblingTexts: string[];
  /** ARIA-label on the element itself, if any. */
  ariaLabel?: string;
  /** ARIA-role on the element itself, if any. */
  role?: string;
  /** `data-testid` attribute – the most stable signal when present. */
  dataTestId?: string;
  /** Text of the `<label>` associated with this element (via `for=` or
   *  by wrapping). Highly valuable for form fields. */
  labelText?: string;
}

/**
 * Persistent record describing a single interactive element.
 *
 * The engine reconstructs this element against the live DOM during a
 * healing attempt, scoring every candidate node against these fields.
 */
export interface ElementMetaData {
  /** Stable, user-defined identifier for the element (e.g. "checkout.submitButton"). */
  logicalName: string;
  /** The selector that last worked. Takes precedence over hard-coded hints. */
  primarySelector: string;
  /** Lower-cased HTML tag (button, input, a, ...). */
  tagName: string;
  /** DOM id at capture time, if present. */
  id?: string;
  /** Tokenised class list at capture time. */
  classes: string[];
  /** Normalised inner text at capture time. */
  textContent: string;
  /** Flat attribute map captured verbatim. */
  attributes: Record<string, string>;
  /** Surrounding DOM context – see {@link AnchorContext}. */
  anchorContext: AnchorContext;
  /** ISO timestamp of the last successful capture. */
  capturedAt: string;
  /** URL pathname so the same logical name can exist on multiple pages. */
  pageUrlPattern?: string;
  /** Rolling audit log of selectors that previously pointed here. */
  healedFrom?: string[];
}

/**
 * Everything needed to re-run a heal decision offline (`selfheal replay`).
 */
export interface HealReplay {
  /** The stored fingerprint the engine scored against (pre-heal). */
  meta: ElementMetaData;
  /** The DOM the engine scored, exactly as serialised for it. */
  dom: string;
  /** The engine's pick in `toLocatorString` form; absent if it found none. */
  engineSelector?: string;
  /** True when embedding similarity shaped the decision – a lexical-only
   *  replay cannot reproduce it. */
  embeddings?: boolean;
}

/**
 * Result of a single interaction attempt, consumed by {@link StateReporter}.
 */
export interface HealingOutcome {
  logicalName: string;
  originalSelector: string;
  healedSelector?: string;
  /** Confidence in the heal – in [0, 1]. 1 means the original matched. */
  confidence: number;
  strategy: 'exact' | 'healed' | 'failed';
  /** Human-readable explanation, useful for debugging flaky heals. */
  reason?: string;
  durationMs: number;
  timestamp: string;
  /** Present on every outcome produced after the DOM was read. */
  // shortcut: DOM is inlined in the report JSON; move to sidecar files if reports grow large.
  replay?: HealReplay;
}
